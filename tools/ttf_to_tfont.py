#!/usr/bin/env python3
"""Rasterise an 8 px pixel font (TTF) into a libtonc 1bpp TFont, as C source.

    python3 tools/ttf_to_tfont.py FONT.ttf SYMBOL OUT.c [--first 32] [--count 96]

The output is a const TFont named SYMBOL plus its glyph array, laid out exactly like libtonc's own
sys8Font (8x8 cells, 1 bit per pixel, one byte per row, least significant bit = leftmost pixel),
so it drops into tte_init_se()/tte_init_chr4c() in place of the default font.

Press Start 2P (assets/fonts, SIL OFL 1.1) is drawn on an 8-unit grid, so rendering at 8 px is
exact: no anti-aliasing decisions are made here. The script checks that and fails otherwise.
Output is deterministic (same input -> byte-identical file).
Needs Pillow with FreeType (Debian/Ubuntu: python3-pil).
"""
import argparse
import os
import sys

from PIL import Image, ImageDraw, ImageFont

CELL = 8


def glyph_rows(font, ch):
    """Return CELL row bytes for one character (bit x set = pixel x lit)."""
    img = Image.new('L', (CELL, CELL), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    rows = []
    for y in range(CELL):
        b = 0
        for x in range(CELL):
            v = img.getpixel((x, y))
            if v not in (0, 255):
                raise ValueError(f'{ch!r}: pixel ({x},{y}) = {v}; the font is not on an {CELL} px grid')
            if v:
                b |= 1 << x
        rows.append(b)
    return rows


def build(ttf, first, count):
    font = ImageFont.truetype(ttf, CELL)
    glyphs = []
    for code in range(first, first + count):
        glyphs.append(glyph_rows(font, chr(code)))
    return glyphs


def to_c(glyphs, symbol, first, ttf):
    words = []
    for rows in glyphs:
        for half in (rows[:4], rows[4:]):
            words.append(half[0] | half[1] << 8 | half[2] << 16 | half[3] << 24)
    name = os.path.basename(ttf)
    out = [
        f'// Generated by tools/ttf_to_tfont.py from {name}: do not edit.',
        '// Glyphs rendered from Press Start 2P (SIL Open Font License 1.1, assets/fonts/OFL.txt).',
        '#include <tonc.h>',
        '',
        f'extern const TFont {symbol};',
        '',
        f'static const u32 {symbol}_glyphs[{len(words)}] __attribute__((aligned(4))) = {{',
    ]
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join(f'0x{w:08X}' for w in words[i:i + 8]) + ',')
    out += [
        '};',
        '',
        f'const TFont {symbol} = {{',
        f'    .data = {symbol}_glyphs,',
        '    .widths = NULL,',
        '    .heights = NULL,',
        f'    .charOffset = {first},',
        f'    .charCount = {len(glyphs)},',
        f'    .charW = {CELL},',
        f'    .charH = {CELL},',
        f'    .cellW = {CELL},',
        f'    .cellH = {CELL},',
        f'    .cellSize = {CELL},',
        '    .bpp = 1,',
        '    .extra = 0,',
        '};',
        '',
    ]
    return '\n'.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('ttf')
    ap.add_argument('symbol')
    ap.add_argument('out')
    ap.add_argument('--first', type=int, default=32)
    ap.add_argument('--count', type=int, default=96)
    a = ap.parse_args(argv)
    try:
        glyphs = build(a.ttf, a.first, a.count)
    except ValueError as e:
        print(f'ttf_to_tfont: {e}', file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as f:
        f.write(to_c(glyphs, a.symbol, a.first, a.ttf))
    return 0


if __name__ == '__main__':
    sys.exit(main())
